#!/usr/bin/env python3
"""Expand the maintained sources into one independently compilable C++ entry."""
from pathlib import Path
import re
import zipfile

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "bots" / "haowen"
OUTPUT = ROOT / "submission"


def standalone_source():
    def expand(path):
        lines = []
        for line in path.read_text(encoding="utf-8").splitlines(keepends=True):
            match = re.fullmatch(r'\s*#include "([^"\n]+)"\s*', line)
            if match:
                header = path.parent / match.group(1)
                lines.append("\n// Begin embedded " + header.name + "\n")
                lines.append(expand(header))
                lines.append("\n// End embedded " + header.name + "\n")
            elif line.strip() != "#pragma once":
                lines.append(line)
        return "".join(lines)

    return ("// Single-file submission: Haowen Aegis, C++17.\n"
            "// Build: c++ -std=c++17 -O2 bot.cpp -o bot\n"
            "// Generated by tools/package_bot.py; strategy is unchanged.\n"
            + expand(SOURCE / "bot.cpp"))


def main():
    OUTPUT.mkdir(exist_ok=True)
    source = standalone_source()
    cpp = OUTPUT / "bot.cpp"
    cpp.write_text(source, encoding="utf-8")
    archive = OUTPUT / "haowen-single-cpp.zip"
    with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED) as z:
        z.writestr("haowen/bot.cpp", source)
    print(cpp)
    print(archive)


if __name__ == "__main__":
    main()
